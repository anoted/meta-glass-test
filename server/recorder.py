"""Session recorder: writes every message from every source to disk.

Layout of one session (recordings/<name>/):

    session.json            summary: start/end, sources, per-stream counts, markers
    events.jsonl            every JSON message, with _rx (server receive ms) and _src
    streams/<src>.<stream>.jsonl   one line per sample, per stream
    csv/<src>.<stream>.csv  same data as CSV (written on finalize)
    media/<src>_video.h265  raw Annex-B HEVC from the DAT camera stream
    media/<src>_video_frames.csv   per-chunk timing (device pts, server rx)
    media/<src>_video.mp4   remuxed on finalize (ffmpeg)
    media/<src>_audio.wav   PCM16 from the DAT audio stream
    media/<src>_frames/     JPEG frames (web camera, if the runtime ever allows it)
    media/<src>_photos/     still photos captured through DAT
    media/<src>_audio.webm  web MediaRecorder audio (if the runtime ever allows it)
    report.html             generated by tools/report.py on finalize
"""

from __future__ import annotations

import csv
import json
import logging
import re
import shutil
import subprocess
import time
import wave
from datetime import datetime
from pathlib import Path

log = logging.getLogger("recorder")

KIND_HEVC = 1
KIND_PCM16 = 2
KIND_JPEG = 3
KIND_PHOTO = 4
KIND_WEBM = 5
KIND_TPUT = 9

_SAFE = re.compile(r"[^A-Za-z0-9_.-]+")


def safe(name: str) -> str:
    return _SAFE.sub("_", str(name))[:64] or "x"


def now_ms() -> float:
    return time.time() * 1000.0


class Session:
    def __init__(self, root: Path, label: str = ""):
        stamp = datetime.now().strftime("%Y-%m-%d_%H-%M-%S")
        self.name = stamp + (f"_{safe(label)}" if label else "")
        self.dir = root / self.name
        (self.dir / "streams").mkdir(parents=True, exist_ok=True)
        (self.dir / "media").mkdir(exist_ok=True)
        self.t_start = now_ms()
        self.t_end: float | None = None
        self.events = open(self.dir / "events.jsonl", "a", buffering=1 << 16)
        self.stream_files: dict[str, object] = {}
        self.counts: dict[str, int] = {}
        self.sources: dict[str, dict] = {}
        self.markers: list[dict] = []
        self.media: dict[str, object] = {}
        self.bytes_written = 0
        self.closed = False
        self._write_summary()

    # ---------------------------------------------------------------- writers
    def _stream(self, key: str):
        f = self.stream_files.get(key)
        if f is None:
            f = open(self.dir / "streams" / f"{key}.jsonl", "a", buffering=1 << 16)
            self.stream_files[key] = f
        return f

    def write_event(self, src: str, msg: dict, rx: float) -> None:
        if self.closed:
            return
        rec = dict(msg)
        rec["_rx"] = round(rx, 3)
        rec["_src"] = src
        t = msg.get("t")
        if t == "batch":
            items = msg.get("items") or []
            for it in items:
                self.write_item(src, it, rx)
            # keep events.jsonl compact: batches are already in streams/
            rec = {"t": "batch", "_rx": rec["_rx"], "_src": src, "n": len(items)}
        elif t == "hello":
            self.sources.setdefault(src, {}).update(
                {"hello": msg, "first_seen": self.sources.get(src, {}).get("first_seen", rx)}
            )
        elif t == "marker":
            self.markers.append({"src": src, "label": msg.get("label", ""), "rx": rx})
        line = json.dumps(rec, separators=(",", ":"))
        self.events.write(line + "\n")
        self.bytes_written += len(line) + 1
        if t in ("caps", "test", "test_suite", "nb_test"):
            self._write_json_artifact(src, msg)

    def write_item(self, src: str, item: dict, rx: float) -> None:
        stream = safe(item.get("s", "unknown"))
        key = f"{safe(src)}.{stream}"
        rec = dict(item)
        rec["_rx"] = round(rx, 3)
        line = json.dumps(rec, separators=(",", ":"))
        self._stream(key).write(line + "\n")
        self.bytes_written += len(line) + 1
        self.counts[key] = self.counts.get(key, 0) + 1

    def _write_json_artifact(self, src: str, msg: dict) -> None:
        t = msg["t"]
        if t == "caps":
            p = self.dir / f"{safe(src)}_capabilities.json"
            p.write_text(json.dumps(msg, indent=2))
        else:
            with open(self.dir / f"{safe(src)}_tests.jsonl", "a") as f:
                f.write(json.dumps(msg) + "\n")

    def write_binary(self, src: str, kind: int, ts: float, meta: dict, payload: bytes, rx: float) -> None:
        if self.closed:
            return
        s = safe(src)
        media = self.dir / "media"
        if kind == KIND_HEVC:
            key = f"{s}_video"
            f = self.media.get(key)
            if f is None:
                f = open(media / f"{s}_video.h265", "ab")
                self.media[key] = f
                idx = open(media / f"{s}_video_frames.csv", "a", newline="")
                self.media[key + "_idx"] = idx
                csv.writer(idx).writerow(["chunk", "device_pts_us", "phone_ms", "server_rx_ms", "bytes", "codec_config", "w", "h"])
                self.media[key + "_n"] = 0
            f.write(payload)
            n = self.media[key + "_n"] = self.media[key + "_n"] + 1
            csv.writer(self.media[key + "_idx"]).writerow(
                [n, meta.get("pts"), round(ts, 3), round(rx, 3), len(payload), int(bool(meta.get("cfg"))), meta.get("w"), meta.get("h")]
            )
            self.counts[f"{s}.video_chunks"] = n
        elif kind == KIND_PCM16:
            key = f"{s}_audio"
            w = self.media.get(key)
            if w is None:
                w = wave.open(str(media / f"{s}_audio.wav"), "wb")
                w.setnchannels(int(meta.get("ch", 1)))
                w.setsampwidth(2)
                w.setframerate(int(meta.get("sr", 16000)))
                self.media[key] = w
                idx = open(media / f"{s}_audio_chunks.csv", "a", newline="")
                csv.writer(idx).writerow(["device_pts_us", "phone_ms", "server_rx_ms", "bytes"])
                self.media[key + "_idx"] = idx
            w.writeframes(payload)
            csv.writer(self.media[key + "_idx"]).writerow([meta.get("pts"), round(ts, 3), round(rx, 3), len(payload)])
            self.counts[f"{s}.audio_bytes"] = self.counts.get(f"{s}.audio_bytes", 0) + len(payload)
        elif kind in (KIND_JPEG, KIND_PHOTO):
            sub = "frames" if kind == KIND_JPEG else "photos"
            d = media / f"{s}_{sub}"
            d.mkdir(exist_ok=True)
            ext = meta.get("ext", "jpg")
            ext = ext if ext in ("jpg", "jpeg", "png", "heic", "webp") else "bin"
            n = self.counts.get(f"{s}.{sub}", 0) + 1
            (d / f"{n:06d}_{int(ts)}.{ext}").write_bytes(payload)
            self.counts[f"{s}.{sub}"] = n
        elif kind == KIND_WEBM:
            key = f"{s}_webm"
            f = self.media.get(key)
            if f is None:
                f = open(media / f"{s}_audio.webm", "ab")
                self.media[key] = f
            f.write(payload)
            self.counts[f"{s}.webm_bytes"] = self.counts.get(f"{s}.webm_bytes", 0) + len(payload)
        else:
            return
        self.bytes_written += len(payload)

    def note_source(self, src: str, **kv) -> None:
        self.sources.setdefault(src, {}).update(kv)

    # ---------------------------------------------------------------- summary
    def summary(self) -> dict:
        return {
            "name": self.name,
            "start_ms": self.t_start,
            "end_ms": self.t_end,
            "duration_s": round(((self.t_end or now_ms()) - self.t_start) / 1000, 2),
            "sources": {k: {kk: vv for kk, vv in v.items() if kk != "hello"} | {"hello": v.get("hello")} for k, v in self.sources.items()},
            "counts": self.counts,
            "markers": self.markers,
            "bytes": self.bytes_written,
            "closed": self.closed,
        }

    def _write_summary(self) -> None:
        (self.dir / "session.json").write_text(json.dumps(self.summary(), indent=2, default=str))

    def flush(self) -> None:
        if self.closed:
            return
        self.events.flush()
        for f in self.stream_files.values():
            f.flush()
        for k, f in self.media.items():
            if hasattr(f, "flush"):
                f.flush()
        self._write_summary()

    def close(self) -> None:
        if self.closed:
            return
        self.t_end = now_ms()
        self.events.close()
        for f in self.stream_files.values():
            f.close()
        for k, f in self.media.items():
            if hasattr(f, "close"):
                try:
                    f.close()
                except Exception:  # noqa: BLE001
                    log.exception("closing %s", k)
        self.closed = True
        self._write_summary()


# -------------------------------------------------------------------- finalize
def jsonl_to_csv(src: Path, dst: Path) -> int:
    rows = []
    keys: dict[str, None] = {}
    with open(src) as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                r = json.loads(line)
            except json.JSONDecodeError:
                continue
            flat = {}
            for k, v in r.items():
                if isinstance(v, dict):
                    for kk, vv in v.items():
                        flat[f"{k}.{kk}"] = vv
                elif isinstance(v, list):
                    flat[k] = json.dumps(v)
                else:
                    flat[k] = v
            for k in flat:
                keys.setdefault(k, None)
            rows.append(flat)
    with open(dst, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(keys))
        w.writeheader()
        w.writerows(rows)
    return len(rows)


def finalize(session_dir: Path) -> None:
    """Convert streams to CSV, remux HEVC to MP4, build the HTML report."""
    session_dir = Path(session_dir)
    csv_dir = session_dir / "csv"
    csv_dir.mkdir(exist_ok=True)
    for p in sorted((session_dir / "streams").glob("*.jsonl")):
        try:
            jsonl_to_csv(p, csv_dir / (p.stem + ".csv"))
        except Exception:  # noqa: BLE001
            log.exception("csv %s", p)
    ffmpeg = shutil.which("ffmpeg")
    for h in (session_dir / "media").glob("*_video.h265"):
        if not ffmpeg or h.stat().st_size == 0:
            continue
        fps = _estimate_fps(h.with_name(h.name.replace(".h265", "_frames.csv")))
        mp4 = h.with_suffix(".mp4")
        cmd = [ffmpeg, "-y", "-loglevel", "error", "-r", f"{fps:.3f}", "-f", "hevc", "-i", str(h), "-c", "copy", "-tag:v", "hvc1", str(mp4)]
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode != 0:
            log.warning("ffmpeg remux failed: %s", r.stderr[-400:])
    try:
        import sys

        sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "tools"))
        import report  # type: ignore

        report.build_report(session_dir)
    except Exception:  # noqa: BLE001
        log.exception("report for %s", session_dir)


def _estimate_fps(idx: Path) -> float:
    try:
        with open(idx) as f:
            rows = list(csv.DictReader(f))
        pts = [float(r["device_pts_us"]) for r in rows if r.get("device_pts_us") not in (None, "", "None") and r.get("codec_config") == "0"]
        if len(pts) > 2 and pts[-1] > pts[0]:
            return max(1.0, min(60.0, (len(pts) - 1) / ((pts[-1] - pts[0]) / 1e6)))
        rx = [float(r["server_rx_ms"]) for r in rows if r.get("codec_config") == "0"]
        if len(rx) > 2 and rx[-1] > rx[0]:
            return max(1.0, min(60.0, (len(rx) - 1) / ((rx[-1] - rx[0]) / 1e3)))
    except Exception:  # noqa: BLE001
        pass
    return 24.0
